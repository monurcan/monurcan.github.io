"""Regenerate the optimized images in assets/ from old/static/ (the previous site's originals).

Run from the repository root:

    python3 tools/make_assets.py

Needs Pillow and (for the POEM clip and frames) ffmpeg. Outputs WebP thumbnails,
the cropped portrait, the 64x64 grayscale target for the in-browser phase retrieval
demo (a lossless data URI, so it also works from file://), the real examples used
by the research figures, and a smaller copy of the POEM video with a poster frame.
"""
import base64
import io
import pathlib
import shutil
import subprocess

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "old" / "static"
OUT = ROOT / "assets"
IMG = OUT / "img"
IMG.mkdir(parents=True, exist_ok=True)
(OUT / "js").mkdir(parents=True, exist_ok=True)
(OUT / "video").mkdir(parents=True, exist_ok=True)


def webp(im, path, width=None, quality=80):
    im = im.convert("RGB")
    if width and im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    im.save(path, "WEBP", quality=quality, method=6)
    return im.size


def cover(im, w, h, fy=0.5):
    """Resize and crop to exactly w x h, like CSS object-fit: cover; fy anchors the vertical crop."""
    im = im.convert("RGB")
    s = max(w / im.width, h / im.height)
    im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
    x, y = (im.width - w) // 2, round((im.height - h) * fy)
    return im.crop((x, y, x + w, y + h))


# --- portrait -----------------------------------------------------------------
src = Image.open(SRC / "images" / "profile.png").convert("RGB")
cx, cy, s = 495, 590, 760  # head-and-shoulders square crop
crop = src.crop((cx - s // 2, cy - s // 2, cx + s // 2, cy + s // 2))
for w in (320, 640):
    webp(crop.resize((w, w), Image.LANCZOS), IMG / f"portrait-{w}.webp", quality=82)

# 64x64 grayscale ground truth for the phase-retrieval demo (Fig. 4), lossless so every browser
# runs HIO on exactly the same numbers (the default random starts were chosen on this image).
gray64 = crop.convert("L").resize((64, 64), Image.LANCZOS)
buf = io.BytesIO()
gray64.save(buf, "PNG", optimize=True)
uri = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
(OUT / "js" / "portrait-data.js").write_text(
    "/* 64x64 grayscale portrait: the hidden ground truth for Fig. 4. Generated by tools/make_assets.py */\n"
    f'window.PORTRAIT_GRAY64="{uri}";\n'
)

# --- publication thumbnails ---------------------------------------------------
singles = ["efficienttesttimescaling", "vartts", "batchparscale", "autoqvis", "prnet", "i2ipr"]
for name in singles:
    im = Image.open(SRC / "images" / f"{name}.png")
    for w in (480, 960):
        webp(im, IMG / f"{name}-{w}.webp", width=w)

frames = [f"wildlight_{i}" for i in range(5)] + [f"ddrmpr_{i}" for i in range(3)]
for name in frames:
    webp(Image.open(SRC / "images" / f"{name}.png"), IMG / f"{name}.webp", quality=82)
for name in ("simit_0", "simit_1"):
    webp(Image.open(SRC / "images" / f"{name}.webp"), IMG / f"{name}.webp", width=640, quality=85)

# --- POEM clip: 960px wide, no audio, fast start + poster of the final frame ----
mp4 = SRC / "videos" / "poem.mp4"
if shutil.which("ffmpeg"):
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(mp4), "-an", "-vf", "scale=960:-2",
                    "-c:v", "libx264", "-crf", "26", "-preset", "slow", "-pix_fmt", "yuv420p",
                    "-movflags", "+faststart", str(OUT / "video" / "poem.mp4")], check=True)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-sseof", "-0.1", "-i", str(mp4), "-frames:v", "1",
                    "-vf", "scale=960:-2", str(IMG / "poem-poster.png")], check=True)
    webp(Image.open(IMG / "poem-poster.png"), IMG / "poem-poster.webp")
    (IMG / "poem-poster.png").unlink()

# --- Fig. 2: real TTAug example (ChartQA) from the project page: 16 inputs (15 altered + original) as one sprite
samples = ROOT / "efficient_test_time_scaling" / "static" / "images" / "samples"
grid = Image.open(samples / "saved_inputs" / "ChartQA_TEST" / "image_grid.jpg").convert("RGB")
cw, ch = grid.width / 4, grid.height / 4
sprite = Image.new("RGB", (800, 560))  # 200x140 tiles, the chart's aspect
for r in range(4):
    for c in range(4):
        tile = grid.crop((round(c * cw) + 3, round(r * ch) + 3, round((c + 1) * cw) - 3, round((r + 1) * ch) - 3))
        sprite.paste(tile.resize((200, 140), Image.LANCZOS), (c * 200, r * 140))
sprite.save(IMG / "ttaug-views.webp", "WEBP", quality=74, method=6)
webp(cover(Image.open(samples / "chartqa_1423.jpg"), 192, 144), IMG / "ttaug-original.webp", quality=86)  # shown at 96x72

# --- Fig. 1: the real SIMIT example (VizWiz query + two imagined practice images)
simit_samples = ROOT / "simit" / "static" / "img" / "samples"
webp(cover(Image.open(simit_samples / "vizwiz_vqa_val_345_query.webp"), 192, 144, 0.55), IMG / "simit-query.webp", quality=82)  # shown at 96x72
for k in (1, 2):
    webp(cover(Image.open(simit_samples / f"vizwiz_vqa_val_345_syn{k}.webp"), 112, 112), IMG / f"simit-syn{k}.webp", quality=82)  # shown at 56x56

# --- Fig. 3: POEM before/after, cropped from the last frame of the original clip
if shutil.which("ffmpeg"):
    last = OUT / "poem-last.png"
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-sseof", "-0.1", "-i", str(mp4), "-frames:v", "1", str(last)], check=True)
    frame = Image.open(last).convert("RGB")
    f = frame.width / 960
    for name, box in (("before", (25, 124, 219, 319)), ("after", (755, 182, 949, 376))):  # inset past the frame borders
        webp(cover(frame.crop(tuple(int(v * f) for v in box)), 420, 420), IMG / f"poem-{name}.webp", quality=82)  # shown about square
    last.unlink()

# --- Relighting figure: each WildLight capture = HDR environment map (rows 24-171) + the real photo (176+)
for i in range(5):
    frame = Image.open(SRC / "images" / f"wildlight_{i}.png").convert("RGB")
    webp(frame.crop((0, 178, frame.width, frame.height)), IMG / f"relight-{i}.webp", quality=86)
    webp(frame.crop((0, 26, frame.width, 170)), IMG / f"relight-env-{i}.webp", quality=86)

shutil.copy(SRC / "images" / "favicon.ico", ROOT / "favicon.ico")  # the original favicon, served from the site root
print("done:", sorted(p.name for p in IMG.iterdir()))
